//! **First contact, cold, against a real log, a real witness and a real relay.**
//!
//! This is the acceptance criterion for `WIRE.md` §12.6 and the end of §12.5's
//! *"dependency, flagged rather than invented"*. Two people who have never
//! spoken open a conversation and exchange messages both ways, and nothing in
//! the path is a fixture:
//!
//! | Piece | What it really is |
//! |---|---|
//! | The directory | `f2z_kt::LogService` — real `akd` trees, a real VRF, real Ed25519, real protobuf inclusion proofs, real epochs. |
//! | The witness | `f2z_witness::Witness` — it verifies the append-only proof before it cosigns, and the client's threshold is applied to what it produced. |
//! | The lookup | `KtClient::resolve` — §6.3's monotonicity rules, §8.3's threshold, the inclusion proof, the pin. The shipping client, unchanged. |
//! | The relay | `FakeRelay` over a **real `ws://127.0.0.1:0` socket**, driven through `connection::drive` and `engine::Relay`. |
//! | The key packages | Really generated by OpenMLS, really published with `PUBLISH_KEY_PACKAGES`, really claimed with `CLAIM_KEY_PACKAGE` behind a proof-of-work stamp. |
//! | The crypto | Real MLS under `MLS_256_XWING_CHACHA20POLY1305_SHA256_Ed25519`: a real `Welcome`, a real join, real `PrivateMessage`s. |
//!
//! # What "two independent instances" means here
//!
//! Two `MlsEngine`s over two separate stores, two separate `DeviceSigner`s, two
//! separate identities, two separate relay connections and two separate
//! `KtClient`s over two separate transports and pin stores. Nothing is shared
//! but the log, the witness and the relay — which is what they are supposed to
//! share. The bytes that cross between them are the bytes that would cross a
//! network: an encoded `DirectoryEntry` in the log's tree, a key package in the
//! relay's pool, a `Welcome`, and `PrivateMessage`s.
//!
//! They are not two *processes*. The plugin's `tests/two_instances_over_a_relay.rs`
//! is, and it drives the same `start_conversation` and `accept_contact_request`
//! over the same wire commands — what it cannot carry is the AGPL log and
//! witness, because `tauri-plugin-f2zmsg` is on the client side of
//! `rs/README.md`'s licence boundary. Between the two files every part of the
//! claim is exercised for real; neither file alone carries all of it, and this
//! is said here rather than implied.
//!
//! # The assertion that makes this more than "it did not panic"
//!
//! Alice never learns Bob's key package from Bob. She learns his *handle*, and
//! everything else is derived: the log proves his `DirectoryEntry`, the entry
//! names his `contact_addr`, the relay serves a package from the pool at that
//! address, and the package is authenticated **against the entry the log
//! proved**. `a_substituted_key_package_is_refused` is the same run with a
//! second, perfectly valid identity's package served in place of Bob's, and it
//! is refused — which is the property that makes putting key packages at an
//! untrusted relay sound at all.

