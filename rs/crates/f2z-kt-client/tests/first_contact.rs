#[test]
fn two_instances_open_a_conversation_from_nothing_but_a_handle() {
    let mut deployment = Deployment::new("first-contact");
    deployment.cosign(NOW);

    let relay_runtime = tokio::runtime::Runtime::new().unwrap();
    let (relay, server, url) = relay_runtime.block_on(async {
        let relay = FakeRelay::with_defaults().unwrap();
        let server = relay.listen_loopback().await.unwrap();
        let url = server.url();
        (relay, server, url)
    });

    // --- cold start: two devices that have never heard of each other --------
    let (alice, bob, mut alice_relay, mut bob_relay, pool) = relay_runtime.block_on(async {
        let alice = Device::enroll("alice", 0x11, 0xa1, &relay).await;
        let bob = Device::enroll("bob", 0x22, 0xb2, &relay).await;
        let mut alice_relay = relay.client().await.unwrap();
        let mut bob_relay = relay.client().await.unwrap();
        // §12.6: Bob publishes a pool before anyone has asked for one.
        let pool = bob.publish_key_packages(&mut bob_relay, 4).await;
        // Alice publishes hers too — first contact is symmetric, and a device
        // that only publishes when it is about to be contacted has published
        // too late.
        let _ = alice.publish_key_packages(&mut alice_relay, 4).await;
        (alice, bob, alice_relay, bob_relay, pool)
    });
    assert_eq!(pool, 4, "the relay holds what bob published");

    // --- both submit their directory entries, and the witness cosigns -------
    deployment.submit(
        &alice.entry(deployment.harness.log_id, &url),
        &alice.identity,
    );
    deployment.submit(&bob.entry(deployment.harness.log_id, &url), &bob.identity);
    deployment.cosign(NOW + 1);

    // --- step 1: alice resolves "bob" through the real client ---------------
    let mut alice_kt = deployment.client();
    let bob_entry = resolve(&mut alice_kt, "bob", NOW + 2);
    let published_contact_addr = QueueAddress::from_slice(
        bob_entry.contact_endpoints.as_slice()[0]
            .contact_addr
            .as_bytes(),
    )
    .unwrap();
    assert_eq!(
        published_contact_addr, bob.contact_addr,
        "the log published the address the relay actually issued"
    );

    // --- step 2: alice claims a key package from that address ---------------
    let claimed = relay_runtime.block_on(async {
        let pow = alice_relay
            .capabilities()
            .await
            .unwrap()
            .capabilities
            .claim_key_package_pow;
        alice_relay
            .claim_key_package(published_contact_addr, Some(pow))
            .await
            .unwrap()
    });
    assert_eq!(
        claimed.last_resort, 0,
        "bob's pool is not empty, so this is a single-use package"
    );

    // --- step 3: and authenticates it against the entry the log proved ------
    let verified = alice
        .mls
        .verify_key_package(claimed.key_package.as_slice(), &bob_entry, NOW + 3)
        .expect("bob's own package, vouched for by the entry bob's handle resolves to");
    assert!(!verified.last_resort());
    assert_eq!(
        verified.device_pk(),
        bob.credential.credential.device_pk.as_bytes()
    );

    // --- step 4: the group, the Welcome, and the conversation ---------------
    let mut alice_group = alice.mls.create_group(b"alice-bob").unwrap();
    let (_commit, welcome) = alice
        .mls
        .add_member(&mut alice_group, &verified, NOW + 4)
        .unwrap();

    // Bob's side. He resolves alice through his own client — §6.4 puts
    // accepting a first-contact Welcome in the same row as resolving a new
    // handle — and then joins.
    let mut bob_kt = deployment.client();
    let alice_entry = resolve(&mut bob_kt, "alice", NOW + 5);
    assert_eq!(
        alice_entry.identity_pk, alice.identity.isk.public,
        "bob confirmed whose Welcome this is against a cosigned root"
    );
    let mut bob_group = bob.mls.join_from_welcome(&welcome, NOW + 6).unwrap();

    assert_eq!(alice_group.group_id(), bob_group.group_id());
    assert_eq!(alice_group.epoch(), bob_group.epoch());

    // Both ways, through real MLS `PrivateMessage`s.
    let wire = alice.mls.send(&mut alice_group, b"hello, bob").unwrap();
    let received = bob
        .mls
        .receive(&mut bob_group, &wire, b"m1", NOW + 7)
        .unwrap();
    assert_eq!(received.payload(), Some(b"hello, bob".as_slice()));

    let reply = bob.mls.send(&mut bob_group, b"hello, alice").unwrap();
    let received = alice
        .mls
        .receive(&mut alice_group, &reply, b"m2", NOW + 8)
        .unwrap();
    assert_eq!(received.payload(), Some(b"hello, alice".as_slice()));

    // --- and the pool really was consumed -----------------------------------
    let second = relay_runtime.block_on(async {
        let pow = bob_relay
            .capabilities()
            .await
            .unwrap()
            .capabilities
            .claim_key_package_pow;
        bob_relay
            .claim_key_package(bob.contact_addr, Some(pow))
            .await
            .unwrap()
    });
    assert_ne!(
        second.key_package.as_slice(),
        claimed.key_package.as_slice(),
        "a claimed package must never be served twice: one init key, one Welcome"
    );

    relay_runtime.block_on(server.shutdown());
}

#[test]
fn a_key_package_whose_credential_is_not_the_directorys_is_refused() {
    // The MITM, with everything else real. A second, perfectly valid identity
    // publishes a perfectly valid pool at its own address; the relay serves one
    // of *its* packages when alice asks about bob. Every check that looks only
    // at the package passes — the signature, the leaf binding, the lifetime, the
    // ciphersuite. Only the directory entry stops it.
    let mut deployment = Deployment::new("first-contact-mitm");
    deployment.cosign(NOW);

    let relay_runtime = tokio::runtime::Runtime::new().unwrap();
    let (relay, server, url) = relay_runtime.block_on(async {
        let relay = FakeRelay::with_defaults().unwrap();
        let server = relay.listen_loopback().await.unwrap();
        let url = server.url();
        (relay, server, url)
    });

    let (alice, bob, mallory, substituted) = relay_runtime.block_on(async {
        let alice = Device::enroll("alice", 0x11, 0xa1, &relay).await;
        let bob = Device::enroll("bob", 0x22, 0xb2, &relay).await;
        let mallory = Device::enroll("mallory", 0x33, 0xc3, &relay).await;
        let mut client = relay.client().await.unwrap();
        let _ = bob.publish_key_packages(&mut client, 2).await;
        let _ = mallory.publish_key_packages(&mut client, 2).await;
        let pow = client
            .capabilities()
            .await
            .unwrap()
            .capabilities
            .claim_key_package_pow;
        // A real claim, from a real pool, at a real address — mallory's.
        let substituted = client
            .claim_key_package(mallory.contact_addr, Some(pow))
            .await
            .unwrap();
        (alice, bob, mallory, substituted)
    });

    deployment.submit(&bob.entry(deployment.harness.log_id, &url), &bob.identity);
    deployment.submit(
        &mallory.entry(deployment.harness.log_id, &url),
        &mallory.identity,
    );
    deployment.cosign(NOW + 1);

    let mut alice_kt = deployment.client();
    let bob_entry = resolve(&mut alice_kt, "bob", NOW + 2);

    let error = alice
        .mls
        .verify_key_package(substituted.key_package.as_slice(), &bob_entry, NOW + 3)
        .expect_err("a package from a different identity must never be usable for @bob");
    // §12.6.5 check 4: the credential does not verify under the entry's
    // `identity_pk`. Reported as a credential failure, never as a transport one
    // — §9 rule 5 forbids proceeding, and a retryable code would invite it.
    assert!(
        matches!(error, f2z_msg_mls::EngineError::Credential(_)),
        "{error:?}"
    );

    // And the honest package for the same handle still works, so the assertion
    // above is about the substitution rather than about the fixture.
    let honest = relay_runtime.block_on(async {
        let mut client = relay.client().await.unwrap();
        let pow = client
            .capabilities()
            .await
            .unwrap()
            .capabilities
            .claim_key_package_pow;
        client
            .claim_key_package(bob.contact_addr, Some(pow))
            .await
            .unwrap()
    });
    alice
        .mls
        .verify_key_package(honest.key_package.as_slice(), &bob_entry, NOW + 4)
        .expect("bob's own package verifies against bob's entry");

    relay_runtime.block_on(server.shutdown());
}

#[test]
fn an_exhausted_pool_falls_back_to_the_last_resort_package_and_then_refuses() {
    // §12.6.6's exhaustion behaviour, end to end and against the real relay: the
    // pool drains, the reusable package carries first contact, and a device that
    // published none is unreachable rather than crashed.
    let mut deployment = Deployment::new("first-contact-exhaustion");
    deployment.cosign(NOW);

    let relay_runtime = tokio::runtime::Runtime::new().unwrap();
    let (relay, server, url) = relay_runtime.block_on(async {
        let relay = FakeRelay::with_defaults().unwrap();
        let server = relay.listen_loopback().await.unwrap();
        let url = server.url();
        (relay, server, url)
    });

    let (alice, bob, spartan) = relay_runtime.block_on(async {
        let alice = Device::enroll("alice", 0x11, 0xa1, &relay).await;
        let bob = Device::enroll("bob", 0x22, 0xb2, &relay).await;
        let spartan = Device::enroll("spartan", 0x44, 0xd4, &relay).await;
        let mut client = relay.client().await.unwrap();
        // Exactly one single-use package, plus a last-resort one.
        let pool = bob.publish_key_packages(&mut client, 1).await;
        assert_eq!(pool, 1);
        // And a device that publishes a pool and **no** last-resort package —
        // §12.6.6's "MAY publish none, accepting unreachability over reuse".
        let packages = spartan.mls.generate_key_packages(1, None).unwrap();
        client
            .publish_key_packages(&spartan.recv_key, spartan.recv_addr, &packages, None)
            .await
            .unwrap();
        (alice, bob, spartan)
    });

    deployment.submit(&bob.entry(deployment.harness.log_id, &url), &bob.identity);
    deployment.submit(
        &spartan.entry(deployment.harness.log_id, &url),
        &spartan.identity,
    );
    deployment.cosign(NOW + 1);

    let mut alice_kt = deployment.client();
    let bob_entry = resolve(&mut alice_kt, "bob", NOW + 2);
    let spartan_entry = resolve(&mut alice_kt, "spartan", NOW + 2);

    relay_runtime.block_on(async {
        let mut client = relay.client().await.unwrap();
        let pow = client
            .capabilities()
            .await
            .unwrap()
            .capabilities
            .claim_key_package_pow;

        // One, and it is single-use.
        let first = client
            .claim_key_package(bob.contact_addr, Some(pow))
            .await
            .unwrap();
        assert_eq!(first.last_resort, 0);

        // Then twice more, and both are the same reusable package — which
        // verifies, and must, because refusing it would convert
        // `THREAT-MODEL.md` §4.12's documented trade into a failure to reach
        // somebody.
        let mut seen = Vec::new();
        for _ in 0..2 {
            let claimed = client
                .claim_key_package(bob.contact_addr, Some(pow))
                .await
                .unwrap();
            assert_eq!(claimed.last_resort, 1, "the relay says the pool is empty");
            let verified = alice
                .mls
                .verify_key_package(claimed.key_package.as_slice(), &bob_entry, NOW + 3)
                .expect("a last-resort package is a valid package from the right device");
            assert!(
                verified.last_resort(),
                "and it says so in its own signed extensions, not only in the relay's byte"
            );
            seen.push(claimed.key_package.as_slice().to_vec());
        }
        assert_eq!(seen[0], seen[1], "the last-resort package is not consumed");

        // The device that published no last-resort package: one claim, then
        // `ERR_UNAVAILABLE`. Not a panic, not an empty success.
        let only = client
            .claim_key_package(spartan.contact_addr, Some(pow))
            .await
            .unwrap();
        alice
            .mls
            .verify_key_package(only.key_package.as_slice(), &spartan_entry, NOW + 3)
            .expect("the one package spartan published");
        let error = client
            .claim_key_package(spartan.contact_addr, Some(pow))
            .await
            .expect_err("an exhausted pool with no last-resort package is a refusal");
        assert!(
            format!("{error}").contains("unavailable")
                || format!("{error:?}").contains("Unavailable"),
            "expected ERR_UNAVAILABLE, got {error:?}"
        );
    });

    relay_runtime.block_on(server.shutdown());
}
