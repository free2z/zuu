// ---------------------------------------------------------------------------
// The socket to the log.
//
// The same shape `tests/acceptance.rs` uses and for the same reason: it encodes
// exactly what `f2z-kt`'s HTTP handlers encode, because it calls exactly what
// they call. Nothing here invents a response.
// ---------------------------------------------------------------------------

struct LogTransport {
    runtime: tokio::runtime::Runtime,
    log: Arc<LogService>,
}

/// A handle onto the transport, so two clients can share one socket to the log
/// the way two devices behind one NAT would.
///
/// A newtype rather than `impl Transport for Arc<LogTransport>`, because the
/// orphan rule forbids implementing this crate's trait for `alloc`'s type.
struct LogHandle(Arc<LogTransport>);

impl LogTransport {
    fn new(log: Arc<LogService>) -> Self {
        Self {
            runtime: tokio::runtime::Builder::new_multi_thread()
                .worker_threads(2)
                .enable_all()
                .build()
                .unwrap(),
            log,
        }
    }
}

impl Transport for LogHandle {
    fn latest_sth(&self) -> f2z_kt_client::Result<Vec<u8>> {
        let bundle = self
            .0
            .runtime
            .block_on(self.0.log.latest_bundle())
            .map_err(|error| ClientError::Unreachable(error.to_string()))?;
        Ok(bundle.encode_canonical().unwrap())
    }

    fn sth_at(&self, epoch: u64) -> f2z_kt_client::Result<Vec<u8>> {
        let bundle = self
            .0
            .runtime
            .block_on(self.0.log.bundle_at(epoch))
            .map_err(|error| ClientError::Unreachable(error.to_string()))?;
        Ok(bundle.encode_canonical().unwrap())
    }

    fn lookup(&self, request: &[u8]) -> f2z_kt_client::Result<Vec<u8>> {
        let decoded =
            f2z_codec::decode_canonical::<f2z_kt_core::api::LookupRequest>(request)?.into_value();
        decoded.validate()?;
        let response = self
            .0
            .runtime
            .block_on(self.0.log.lookup(&decoded.handle))
            .map_err(|error| ClientError::Unreachable(error.to_string()))?;
        Ok(response.encode_canonical().unwrap())
    }

    fn history(&self, request: &[u8]) -> f2z_kt_client::Result<Vec<u8>> {
        let decoded =
            f2z_codec::decode_canonical::<f2z_kt_core::api::HistoryRequest>(request)?.into_value();
        decoded.validate()?;
        let response = self
            .0
            .runtime
            .block_on(self.0.log.history(
                &decoded.handle,
                f2z_kt_core::verify::HistoryParams::Complete,
            ))
            .map_err(|error| ClientError::Unreachable(error.to_string()))?;
        Ok(response.encode_canonical().unwrap())
    }

    fn authority_policy(&self) -> f2z_kt_client::Result<Vec<u8>> {
        Err(ClientError::Unreachable(
            "this fixture serves no policy".to_owned(),
        ))
    }

    fn descriptor(&self) -> f2z_kt_client::Result<Vec<u8>> {
        Err(ClientError::Unreachable(
            "this fixture serves no descriptor".to_owned(),
        ))
    }
}

struct WitnessTransport(Arc<LogTransport>);

impl f2z_witness::Transport for WitnessTransport {
    fn latest_sth(&self) -> f2z_witness::Result<Vec<u8>> {
        let bundle = self
            .0
            .runtime
            .block_on(self.0.log.latest_bundle())
            .map_err(|error| f2z_witness::WitnessError::Transport(error.to_string()))?;
        Ok(bundle.encode_canonical().unwrap())
    }

    fn audit(&self, from: u64, to: u64) -> f2z_witness::Result<Vec<u8>> {
        let response = self
            .0
            .runtime
            .block_on(self.0.log.audit(from, to))
            .map_err(|error| f2z_witness::WitnessError::Transport(error.to_string()))?;
        Ok(response.encode_canonical().unwrap())
    }

    fn cosign(&self, cosignature: &[u8]) -> f2z_witness::Result<()> {
        let decoded = f2z_codec::decode_canonical::<f2z_kt_core::WitnessCosignature>(cosignature)
            .map_err(|error| f2z_witness::WitnessError::Transport(error.to_string()))?
            .into_value();
        self.0
            .runtime
            .block_on(self.0.log.accept_cosignature(&decoded))
            .map_err(|error| f2z_witness::WitnessError::Transport(error.to_string()))
    }
}

// ---------------------------------------------------------------------------
// One device: an identity, an MLS engine, a contact queue, and a published pool.
// ---------------------------------------------------------------------------

/// A device, built the way enrollment builds one.
///
/// The `DeviceCredential` is signed by the identity key that the directory entry
/// publishes, over the **real** MLS signing key — so the entry's `devices` set
/// and the credential inside every key package this device generates are the
/// same bytes. That is the whole precondition for §12.6.5's check to mean
/// anything.
struct Device {
    handle: String,
    identity: Identity,
    credential: DeviceCredential,
    mls: MlsEngine<MemoryBackend>,
    recv_key: SigningKey,
    recv_addr: QueueAddress,
    contact_addr: QueueAddress,
}

fn credential_for(identity: &Identity, handle: &str, device_pk: &[u8; 32]) -> DeviceCredential {
    let tbs = DeviceCredentialTBS {
        label: label_field(labels::LABEL_DEVICE_CREDENTIAL).unwrap(),
        identity_pk: identity.isk.public,
        handle: Handle::new(handle.as_bytes().to_vec()).unwrap(),
        device_pk: PublicKey::new(*device_pk),
        // Not read by MLS — the HPKE init key is the one inside the
        // `KeyPackage`, generated by OpenMLS. `KT.md` §4.1 requires only that it
        // is non-empty.
        device_kem_pk: KemPublicKey::new(vec![0x5a; 1216]).unwrap(),
        not_before_ms: NOW - 1_000_000,
        not_after_ms: NOW + 100_000_000,
    };
    let signature = identity.isk.sign(&tbs.signing_bytes().unwrap());
    DeviceCredential {
        credential: tbs,
        signature,
    }
}

impl Device {
    /// Cold start, in order: keys, then a contact queue on the relay, then MLS.
    ///
    /// The contact queue comes before the directory entry because the entry has
    /// to publish the address the relay issued (§12.2, §12.6). Nothing is
    /// pre-arranged.
    async fn enroll(handle: &str, identity_seed: u8, device_seed: u8, relay: &FakeRelay) -> Self {
        let identity = Identity::from_byte(identity_seed);
        let signer = DeviceSigner::from_private_key([device_seed; 32]);
        let credential = credential_for(&identity, handle, signer.public_key());

        let mls = MlsEngine::new(MemoryBackend::new(), signer, credential.clone(), NOW).unwrap();

        let recv_key = SigningKey::from_seed(&[device_seed.wrapping_add(0x10); 32]);
        let mut client = relay.client().await.unwrap();
        let created = client
            .create_contact_queue(&recv_key, 0, 0, None)
            .await
            .unwrap();

        Self {
            handle: handle.to_owned(),
            identity,
            credential,
            mls,
            recv_key,
            recv_addr: created.recv_addr,
            contact_addr: created.contact_addr,
        }
    }

    /// §12.6: publish a pool and one package of last resort.
    async fn publish_key_packages(&self, client: &mut Client, count: usize) -> u32 {
        let packages = self.mls.generate_key_packages(count, None).unwrap();
        let last_resort = self
            .mls
            .generate_last_resort_key_package(Some(2_592_000))
            .unwrap();
        let published = client
            .publish_key_packages(&self.recv_key, self.recv_addr, &packages, Some(last_resort))
            .await
            .unwrap();
        assert_eq!(published.has_last_resort, 1);
        published.pool_size
    }

    /// The `DirectoryEntry` this device submits: its real credential, and the
    /// real `contact_addr` the relay issued.
    fn entry(
        &self,
        log_id: f2z_kt_core::types::LogId,
        relay_url: &str,
    ) -> f2z_kt_core::entry::DirectoryEntry {
        EntryBuilder::first(log_id, &self.handle, &self.identity)
            .credential(self.credential.clone())
            .contact_endpoint(relay_url, RelayId::new([0x77; 32]), self.contact_addr)
            .same_key(&self.identity.dak)
    }
}

// ---------------------------------------------------------------------------
// The deployment.
// ---------------------------------------------------------------------------

struct Deployment {
    setup: tokio::runtime::Runtime,
    harness: Harness,
    transport: Arc<LogTransport>,
    witness: Witness,
}

impl Deployment {
    fn new(name: &str) -> Self {
        let setup = tokio::runtime::Runtime::new().unwrap();
        let harness = setup.block_on(Harness::vouched_with_witnesses(
            name,
            vec![Key::from_byte(WITNESS_SEED).public],
        ));
        setup.block_on(harness.log.publish_epoch(NOW)).unwrap();

        let transport = Arc::new(LogTransport::new(Arc::clone(&harness.log)));
        let dir = f2z_kt::testing::temp_dir(&format!("{name}-w"));
        let witness = Witness::new(
            Settings {
                log_id: harness.log_id,
                accepted_log_pk: harness.log.log_public_key(),
                state_path: dir.join("state.bin"),
                evidence_dir: dir.join("evidence"),
                max_audit_span: 64,
            },
            &[WITNESS_SEED; 32],
            Box::new(WitnessTransport(Arc::clone(&transport))),
        )
        .unwrap();

        Self {
            setup,
            harness,
            transport,
            witness,
        }
    }

    fn submit(&self, entry: &f2z_kt_core::entry::DirectoryEntry, identity: &Identity) {
        self.setup.block_on(async {
            self.harness
                .log
                .submit(&self.harness.envelope(entry, identity, NOW), NOW)
                .await
                .unwrap();
            self.harness.log.publish_epoch(NOW).await.unwrap();
        });
    }

    fn cosign(&mut self, now_ms: u64) {
        match self.witness.poll_once(now_ms).unwrap() {
            Outcome::Pinned { .. } | Outcome::Cosigned { .. } | Outcome::UpToDate { .. } => {}
            other => panic!("the witness refused to cosign an honest log: {other:?}"),
        }
    }

    /// A client that counts this deployment's witness, with `t = 1`.
    ///
    /// `dependent`, not `independent`: free2z would operate both the log and
    /// this witness, and §8.3 is explicit that such a set carries zero
    /// anti-equivocation value. Claiming independence here would make this a
    /// test of a property the deployment does not have.
    fn client(&self) -> KtClient<LogHandle> {
        let witnesses = WitnessSet::new(
            vec![ConfiguredWitness::dependent(self.witness.public_key())],
            1,
        )
        .unwrap();
        KtClient::bootstrap(
            LogHandle(Arc::clone(&self.transport)),
            ClientConfig {
                log_id: self.harness.log_id,
                accepted_log_pk: self.harness.log.log_public_key(),
                witnesses,
                reset_authority_pk: self.harness.reset_authority.public,
                reset_cooldown_seconds: 60,
            },
        )
        .unwrap()
    }
}

/// Resolve a handle through the real client and hand back the verified entry.
fn resolve(client: &mut KtClient<LogHandle>, handle: &str, now_ms: u64) -> DirectoryEntryTBS {
    let resolution = client
        .resolve(&Handle::new(handle.as_bytes().to_vec()).unwrap(), now_ms)
        .expect("an honest log, a cosigned root and a registered handle");
    let resolved = resolution
        .resolved()
        .expect("the handle is registered, and the log proved it");
    assert!(
        resolution.standing().threshold_met(),
        "the client must not have accepted a root without the threshold"
    );
    resolved.entry().entry.clone()
}

