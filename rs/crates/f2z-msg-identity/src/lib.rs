/// The version of the messaging key hierarchy this crate implements.
///
/// It is not a wire field and nothing serializes it. It exists so that a change
/// to [`labels`]' constants — which changes every user's identity — has an
/// obvious, greppable companion that a reviewer will see move. There is no v2
/// and there is no migration story for one; see the crate note.
