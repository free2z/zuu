TRANSFER_DDL_REVERSE = "DROP TABLE IF EXISTS ledger_transfer CASCADE;"


def partition_name(year, month):
    return f"ledger_transfer_y{year:04d}m{month:02d}"


def month_bounds(year, month):
    start = datetime.datetime(year, month, 1, tzinfo=datetime.timezone.utc)
    if month == 12:
        end = datetime.datetime(year + 1, 1, 1, tzinfo=datetime.timezone.utc)
    else:
        end = datetime.datetime(year, month + 1, 1, tzinfo=datetime.timezone.utc)
    return start, end


def months_from(first, count):
    """``(year, month)`` for ``first`` and the ``count`` months after it."""
    year, month = first
    out = []
    for _ in range(count + 1):
        out.append((year, month))
        month += 1
        if month == 13:
            year, month = year + 1, 1
    return out


def partition_ddl(year, month):
    start, end = month_bounds(year, month)
    return (
        f"CREATE TABLE IF NOT EXISTS {partition_name(year, month)} "
        f"PARTITION OF ledger_transfer FOR VALUES "
        f"FROM ('{start.isoformat()}') TO ('{end.isoformat()}')"
    )


def create_month_partitions(apps, schema_editor):
    if schema_editor.connection.vendor != "postgresql":
        raise RuntimeError("ledger.0001 needs PostgreSQL (partitioned tables)")
    # The database clock, not the migrating host's: the partitions must
    # bracket the rows `now()` will stamp.
    with schema_editor.connection.cursor() as cursor:
        cursor.execute("SELECT date_trunc('month', now() AT TIME ZONE 'UTC')")
        first = cursor.fetchone()[0]
    for year, month in months_from((first.year, first.month), PARTITION_MONTHS_AHEAD):
        schema_editor.execute(partition_ddl(year, month))


def drop_month_partitions(apps, schema_editor):
    # TRANSFER_DDL_REVERSE drops the parent CASCADE, taking every partition.
    return None


