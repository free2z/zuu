FUNCTIONS_SQL = r"""
CREATE FUNCTION ledger.price(p_cost_nusd bigint, p_platform_margin_bps integer,
                            p_dev_markup_bps integer, p_min_charge_2z integer)
RETURNS TABLE (priced bigint, provider_m2z bigint, dev_floor_m2z bigint)
LANGUAGE plpgsql IMMUTABLE SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    total numeric;
    dev numeric;
BEGIN
    IF p_cost_nusd IS NULL OR p_cost_nusd < 0
       OR p_platform_margin_bps IS NULL OR p_platform_margin_bps NOT BETWEEN 0 AND 100000
       OR p_dev_markup_bps IS NULL OR p_dev_markup_bps NOT BETWEEN 0 AND 10000
       OR p_min_charge_2z IS NULL OR p_min_charge_2z < 0 THEN
        RAISE EXCEPTION 'ledger.price: invalid pricing input' USING ERRCODE = '22023';
    END IF;
    total := p_cost_nusd::numeric * (10000 + p_platform_margin_bps) * (10000 + p_dev_markup_bps);
    dev := p_cost_nusd::numeric * (10000 + p_platform_margin_bps) * p_dev_markup_bps;
    priced := (greatest(p_min_charge_2z::numeric, ceil(total / 1000000000000000::numeric)) * 1000)::bigint;
    provider_m2z := ceil(p_cost_nusd::numeric / 10000)::bigint;
    dev_floor_m2z := floor(dev / 1000000000000::numeric)::bigint;
    RETURN NEXT;
END $$;

-- A total cap has one stable window across every re-consent and period edit.
-- Calendar windows are UTC, independent of pooled server session TimeZone.
CREATE FUNCTION ledger.window_start(p_period text, p_at timestamptz)
RETURNS timestamptz
LANGUAGE plpgsql IMMUTABLE SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$ BEGIN
    IF p_period = 'total' THEN RETURN '1970-01-01 00:00:00+00'::timestamptz; END IF;
    IF p_period IS NULL OR p_period NOT IN ('day', 'week', 'month') OR p_at IS NULL THEN
        RAISE EXCEPTION 'ledger.window_start: invalid period or timestamp' USING ERRCODE = '22023';
    END IF;
    RETURN date_trunc(p_period, p_at AT TIME ZONE 'UTC') AT TIME ZONE 'UTC';
END $$;

-- Per-schema default privileges do not remove the global PUBLIC EXECUTE
-- default on PostgreSQL. Revoke explicitly in every function migration.
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA ledger FROM PUBLIC;
"""

