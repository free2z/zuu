#!/usr/bin/env node
//
// Prove that every Tauri plugin's command registry, its generated permissions,
// and the capabilities that grant them all describe the same set of commands.
//
// ## Why this is one script and not one per plugin
//
// It used to be `scripts/check-zcash-permissions.mjs`, hard-coded to
// `tauri-plugin-zcash` in its path, its `zcash:` namespace, its registry macro
// and its consumer's schema directory. `docs/e2ee/CLIENT-CONTRACT.md` §12.3
// anticipated the second plugin and concluded it "has to be written, not
// parameterized: nothing in the existing script generalizes past the hard-coded
// plugin path, namespace and schema directory".
//
// That conclusion was about the script as it stood, and it is exactly the
// reasoning that produces two near-identical checkers which then drift — one
// gets a new assertion and the other does not, and the plugin nobody looked at
// is the one that ships a command with no permission. So the parameters were
// lifted into `PLUGINS` instead. Everything §12.3 said is genuinely different
// between the two plugins is a **field**: the namespace, the registry macro,
// the consuming apps, and whether a consumer tracks generated target schemas at
// all (Zuuallet does; Zuuli tracks none).
//
// ## The chain
//
// For each plugin, a chain of set equalities:
//
//   command_registry.rs
//     ↔ build.rs's consumption of it        (permissions are generated from it)
//     ↔ src/lib.rs's consumption of it      (the runtime invoke handler)
//     ↔ permissions/autogenerated/commands/*.toml
//     ↔ permissions/schemas/schema.json     (the allow-/deny- constants)
//     ↔ permissions/autogenerated/reference.md
//     ↔ permissions/default.toml            (NEW — see below)
//     ↔ each registered capability file     (NEW — see below)
//     ↔ each consuming app's tracked target schemas, where any are tracked
//
// ## The two links that are new, and the gap they close
//
// §2.3 named four places a command must appear and observed that **two of them
// were mechanically enforced and two were not**: nothing derived
// `permissions/default.toml` or any capability file from the command registry,
// and nothing failed when a command was missing from them. It documented the
// gap with a grep proving the old checker never opened either file.
//
// Both are now checked:
//
//   * `permissions/default.toml` must allow **exactly** the registered set. A
//     command missing from it compiles, registers, generates a permission, and
//     is then unreachable from any capability that takes `<plugin>:default` —
//     which is a runtime failure with no build-time symptom at all.
//   * Each registered capability file must grant the plugin either
//     `<plugin>:default` or an exact list of `<plugin>:allow-…` identifiers,
//     every one of which must be a real command. A typo there is the same
//     silent runtime failure from the other end.
//
// Capability *policy* — which commands a mobile webview should have — is not
// this script's business and stays where it is:
// `wallet/zuuli/scripts/mobile-webview-authority.mjs` holds `mobile.json`
// against a hand-maintained reviewed allowlist. Mobile authority is granted by
// review, not by registration. What this script adds is that every identifier
// in that reviewed list is a command that exists.
//
// ## Registration is enforced
//
// `PLUGINS` must cover every `wallet/plugins/*/Cargo.toml` git tracks. A plugin
// added and not registered here would be invisible to this check and would pass
// by having no surface — the same failure mode
// `scripts/check-workflow-gates.mjs` closed for ungated workflows.
//
// Usage:
//   node scripts/check-tauri-plugin-permissions.mjs             judge the tree
//   node scripts/check-tauri-plugin-permissions.mjs --self-test negative controls first

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/// Every plugin under `wallet/plugins/`, and what differs about each.
///
/// `namespace` is the crate name minus its `tauri-plugin-` prefix, which is
/// what `tauri_plugin::Builder` uses to prefix generated identifiers and what
/// `Builder::new(..)` must be given at runtime for a capability to authorize an
/// `invoke`. It is a field rather than derived from the directory name because
/// the two can differ and the identifier is the load-bearing one.
const PLUGINS = [
  {
    directory: "wallet/plugins/tauri-plugin-zcash",
    namespace: "zcash",
    macro: "with_zcash_commands",
    capabilities: [
      {
        file: "wallet/zuuli/src-tauri/capabilities/default.json",
        grant: "default",
      },
      {
        file: "wallet/zuuli/src-tauri/capabilities/mobile.json",
        grant: "named",
      },
      {
        file: "wallet/zuuallet/src-tauri/capabilities/default.json",
        grant: "default",
      },
    ],
    trackedSchemas: {
      directory: "wallet/zuuallet/src-tauri/gen/schemas",
      label: "Zuuallet",
    },
  },
  {
    directory: "wallet/plugins/tauri-plugin-f2zmsg",
    namespace: "f2zmsg",
    macro: "with_f2zmsg_commands",
    // Empty, with a reason, and the reason is not "not yet written".
    //
    // `wallet/zuuli/src-tauri` cannot link this plugin today: librustzcash's
    // `bip32 = "=0.6.0-pre.1"` requires `sha2 = "=0.11.0-pre.4"`, and
    // `ed25519-dalek 3` — which the whole messaging core is on — requires
    // `sha2 ^0.11`, which a pre-release does not satisfy. Cargo unifies
    // semver-compatible versions, so the two cannot coexist, and a capability
    // naming `f2zmsg:` for a plugin the app does not link would fail
    // `tauri_build::build()` rather than protect anything.
    //
    // The moment that conflict lifts, this array gains the two Zuuli capability
    // files and `capabilitiesPending` goes away. `capabilitiesPending` is here
    // so the empty list is a recorded decision rather than an omission: the
    // check below rejects an empty `capabilities` that carries no reason.
    capabilities: [],
    capabilitiesPending:
      "wallet/zuuli/src-tauri cannot link tauri-plugin-f2zmsg while librustzcash's " +
      "bip32 =0.6.0-pre.1 pins sha2 =0.11.0-pre.4 and ed25519-dalek 3 requires sha2 ^0.11",
    // Zuuli tracks no generated target schemas — `git ls-files` over
    // `wallet/zuuli/src-tauri/gen/schemas` is empty — so this plugin has no
    // counterpart for the chain's last link. That asymmetry is §2.3's, not a
    // gap here.
    trackedSchemas: null,
  },
];

/// The shortest string that can pass as a recorded reason. `""` — the thing a
/// hurried edit reaches for — is red rather than a silent exemption.
const MINIMUM_REASON = 60;

function unique(values, label) {
  const duplicates = values.filter((value, index) => values.indexOf(value) !== index);
  if (duplicates.length) {
    throw new Error(`${label} contains duplicates: ${[...new Set(duplicates)].join(", ")}`);
  }
  return [...values].sort();
}

function assertSameSet(expected, actual, label) {
  const expectedSet = new Set(expected);
  const actualSet = new Set(actual);
  const missing = expected.filter((value) => !actualSet.has(value));
  const extra = actual.filter((value) => !expectedSet.has(value));
  if (missing.length || extra.length) {
    throw new Error(
      `${label} drifted` +
        `${missing.length ? `; missing: ${missing.join(", ")}` : ""}` +
        `${extra.length ? `; extra: ${extra.join(", ")}` : ""}`,
    );
  }
}

function collectConsts(value, output = []) {
  if (Array.isArray(value)) {
    for (const item of value) collectConsts(item, output);
  } else if (value && typeof value === "object") {
    if (typeof value.const === "string") output.push(value.const);
    for (const item of Object.values(value)) collectConsts(item, output);
  }
  return output;
}

function assertIdentical(entries, label) {
  const [first, ...rest] = entries;
  const different = rest.filter((entry) => !entry.contents.equals(first.contents));
  if (different.length) {
    throw new Error(
      `${label} differ: ${[first, ...different].map((entry) => entry.name).join(", ")}`,
    );
  }
}

function schemaNamesFromTrackedPaths(listing, schemaDir, label) {
  const prefix = `${schemaDir}/`;
  const names = listing
    .split("\n")
    .filter(Boolean)
    .map((entry) => {
      if (!entry.startsWith(prefix) || !entry.endsWith("-schema.json")) {
        throw new Error(`unexpected tracked ${label} schema path: ${entry}`);
      }
      return entry.slice(prefix.length);
    });
  if (!names.length) throw new Error(`no tracked ${label} target schemas found`);
  return unique(names, `tracked ${label} target schemas`);
}

function commandRegistryNames(source, macroName) {
  if (!source.includes(`macro_rules! ${macroName}`)) {
    throw new Error(`command_registry.rs does not define ${macroName}`);
  }
  const callback = source.match(/\$callback!\s*\{([\s\S]*?)\n\s*\}/);
  if (!callback) throw new Error("could not find shared command registry");
  const body = callback[1];
  const commands = [...body.matchAll(/^\s*([a-z0-9_]+),\s*$/gm)].map((match) => match[1]);
  // Comments are the registry's own section headers (`// §3.1 engine
  // lifecycle`), not syntax, so they are stripped before the residue check —
  // which still rejects anything that is neither a bare identifier nor a
  // comment, because `one => hidden` is how a registry stops meaning what it
  // looks like it means.
  const residue = body
    .replace(/^\s*\/\/.*$/gm, "")
    .replace(/^\s*[a-z0-9_]+,\s*$/gm, "")
    .trim();
  if (residue) throw new Error(`unrecognized shared command registry syntax: ${residue}`);
  if (!commands.length) throw new Error("shared command registry is empty");
  return unique(commands, "shared command registry");
}

/// The `allow-` identifiers `permissions/default.toml` grants.
///
/// Parsed rather than TOML-decoded so the script has no dependency: the file is
/// generated by hand from a fixed template and the shape is a single
/// `permissions = [ … ]` array of quoted strings.
function defaultPermissionIds(source) {
  const block = source.match(/permissions\s*=\s*\[([\s\S]*?)\]/);
  if (!block) throw new Error("permissions/default.toml has no `permissions` array");
  const ids = [...block[1].matchAll(/"([^"]+)"/g)].map((match) => match[1]);
  if (!ids.length) throw new Error("permissions/default.toml grants nothing");
  return unique(ids, "default.toml permissions");
}

/// The identifiers a capability file lists, as plain strings.
///
/// A capability entry is either a bare identifier or an object with one; both
/// are accepted here because scoped permissions (`http:default` with an
/// `allow` list) are legitimate. What is not accepted is a plugin command
/// permission carrying scope data — those take no scope, and one that appeared
/// to would be a reader's mistake waiting to happen.
function capabilityIdentifiers(capability, namespace, file) {
  if (!Array.isArray(capability.permissions)) {
    throw new Error(`${file} has no permissions array`);
  }
  const identifiers = capability.permissions.map((permission) =>
    typeof permission === "string" ? permission : permission?.identifier,
  );
  if (identifiers.some((identifier) => typeof identifier !== "string")) {
    throw new Error(`${file} has a permission with no identifier`);
  }
  const scoped = capability.permissions.filter(
    (permission) =>
      typeof permission === "object" &&
      typeof permission?.identifier === "string" &&
      permission.identifier.startsWith(`${namespace}:`),
  );
  if (scoped.length) {
    throw new Error(
      `${file} gives ${scoped.map((permission) => permission.identifier).join(", ")} scope data; ` +
        "plugin command permissions take none",
    );
  }
  return identifiers.filter((identifier) => identifier.startsWith(`${namespace}:`));
}

function trackedPluginDirectories() {
  const listing = execFileSync("git", ["ls-files", "--", "wallet/plugins/*/Cargo.toml"], {
    cwd: root,
    encoding: "utf8",
  });
  const directories = listing
    .split("\n")
    .filter(Boolean)
    .map((entry) => path.posix.dirname(entry));
  if (!directories.length) throw new Error("no tracked plugin manifests found");
  return unique(directories, "tracked plugin directories");
}

function checkPlugin(plugin) {
  const dir = path.join(root, plugin.directory);
  const { namespace } = plugin;

  const registrySource = fs.readFileSync(path.join(dir, "command_registry.rs"), "utf8");
  const commands = commandRegistryNames(registrySource, plugin.macro);

  const buildSource = fs.readFileSync(path.join(dir, "build.rs"), "utf8");
  if (
    !buildSource.includes('include!("command_registry.rs");') ||
    !buildSource.includes(`${plugin.macro}!(command_names)`)
  ) {
    throw new Error(`${plugin.directory}/build.rs does not consume the shared command registry`);
  }
  const libSource = fs.readFileSync(path.join(dir, "src/lib.rs"), "utf8");
  if (
    !libSource.includes('include!("../command_registry.rs");') ||
    !libSource.includes(`.invoke_handler(${plugin.macro}!(command_handler))`)
  ) {
    throw new Error(
      `${plugin.directory} runtime invoke handler does not consume the shared command registry`,
    );
  }
  // The runtime namespace and the generated one have to be the same string, or
  // a capability grants an identifier no `invoke` will ever match.
  if (!libSource.includes(`Builder::new("${namespace}")`)) {
    throw new Error(
      `${plugin.directory}/src/lib.rs does not register the plugin as "${namespace}"; ` +
        "generated identifiers would not authorize its commands",
    );
  }

  const commandDir = path.join(dir, "permissions/autogenerated/commands");
  const generatedCommands = unique(
    fs
      .readdirSync(commandDir)
      .filter((name) => name.endsWith(".toml"))
      .map((name) => name.slice(0, -5)),
    `${namespace} generated command permissions`,
  );
  assertSameSet(commands, generatedCommands, `${namespace} registered and generated commands`);

  const permissionIds = [];
  const allowIds = [];
  for (const command of commands) {
    const source = fs.readFileSync(path.join(commandDir, `${command}.toml`), "utf8");
    const kebab = command.replaceAll("_", "-");
    const expectedIds = [`allow-${kebab}`, `deny-${kebab}`];
    const actualIds = [...source.matchAll(/^identifier = "([^"]+)"$/gm)].map((match) => match[1]);
    assertSameSet(expectedIds, actualIds, `${namespace} ${command}.toml identifiers`);
    for (const mode of ["allow", "deny"]) {
      if (!source.includes(`commands.${mode} = ["${command}"]`)) {
        throw new Error(`${namespace} ${command}.toml does not ${mode} exactly ${command}`);
      }
    }
    permissionIds.push(...expectedIds);
    allowIds.push(`allow-${kebab}`);
  }

  const permissionSchema = JSON.parse(
    fs.readFileSync(path.join(dir, "permissions/schemas/schema.json"), "utf8"),
  );
  const schemaIds = unique(
    collectConsts(permissionSchema).filter((value) => /^(allow|deny)-/.test(value)),
    `${namespace} permission schema identifiers`,
  );
  assertSameSet(
    permissionIds.slice().sort(),
    schemaIds,
    `${namespace} command TOMLs and permission schema`,
  );

  const reference = fs.readFileSync(
    path.join(dir, "permissions/autogenerated/reference.md"),
    "utf8",
  );
  const referenceIds = unique(
    [...reference.matchAll(new RegExp(`\`${namespace}:((?:allow|deny)-[a-z0-9-]+)\``, "g"))].map(
      (match) => match[1],
    ),
    `${namespace} permission reference identifiers`,
  );
  assertSameSet(permissionIds, referenceIds, `${namespace} command TOMLs and permission reference`);

  // §2.3's third place, unenforced until now.
  const defaultIds = defaultPermissionIds(
    fs.readFileSync(path.join(dir, "permissions/default.toml"), "utf8"),
  );
  assertSameSet(
    allowIds.slice().sort(),
    defaultIds,
    `${namespace} registered commands and permissions/default.toml`,
  );

  // §2.3's fourth place, likewise.
  if (!plugin.capabilities.length) {
    const reason = plugin.capabilitiesPending ?? "";
    if (reason.length < MINIMUM_REASON) {
      throw new Error(
        `${namespace} grants no capability and records no substantive reason; ` +
          "set capabilitiesPending to why, or register the capability files",
      );
    }
  }
  const namespacedAllow = new Set(allowIds.map((identifier) => `${namespace}:${identifier}`));
  for (const entry of plugin.capabilities) {
    const capability = JSON.parse(fs.readFileSync(path.join(root, entry.file), "utf8"));
    const granted = capabilityIdentifiers(capability, namespace, entry.file);
    if (!granted.length) {
      throw new Error(`${entry.file} grants nothing from ${namespace}`);
    }
    if (entry.grant === "default") {
      assertSameSet([`${namespace}:default`], granted, `${entry.file} ${namespace} grant`);
    } else {
      unique(granted, `${entry.file} ${namespace} identifiers`);
      const unknown = granted.filter((identifier) => !namespacedAllow.has(identifier));
      if (unknown.length) {
        throw new Error(
          `${entry.file} grants ${unknown.join(", ")}, which ${namespace} does not register`,
        );
      }
    }
  }

  let schemas = [];
  if (plugin.trackedSchemas) {
    const { directory: schemaRelativeDir, label } = plugin.trackedSchemas;
    const schemaDir = path.join(root, schemaRelativeDir);
    const schemaNames = schemaNamesFromTrackedPaths(
      execFileSync("git", ["ls-files", "--", `${schemaRelativeDir}/*-schema.json`], {
        cwd: root,
        encoding: "utf8",
      }),
      schemaRelativeDir,
      label,
    );
    const expectedAppSchemaIds = [
      ...permissionIds.map((identifier) => `${namespace}:${identifier}`),
      `${namespace}:default`,
    ];
    schemas = schemaNames.map((name) => {
      const contents = fs.readFileSync(path.join(schemaDir, name));
      const schema = JSON.parse(contents);
      const identifiers = unique(
        collectConsts(schema).filter((value) => value.startsWith(`${namespace}:`)),
        `${name} ${namespace} permission identifiers`,
      );
      assertSameSet(expectedAppSchemaIds, identifiers, `${namespace} permissions and ${name}`);
      return { name, contents };
    });
    assertIdentical(schemas, `tracked ${label} target schemas`);
  }

  return { commands, permissionIds, schemas };
}

function expectFailure(fn, pattern) {
  try {
    fn();
  } catch (error) {
    if (pattern.test(String(error))) return;
    throw error;
  }
  throw new Error(`negative control did not fail: ${pattern}`);
}

function selfTest() {
  expectFailure(
    () => assertSameSet(["one", "two"], ["one", "two", "stale"], "permissions"),
    /extra: stale/,
  );
  expectFailure(() => assertSameSet(["one", "two"], ["one"], "permissions"), /missing: two/);
  expectFailure(() => unique(["one", "one"], "commands"), /duplicates: one/);
  expectFailure(
    () => commandRegistryNames("$callback! {\n one,\n one,\n }", "m"),
    /does not define m/,
  );
  expectFailure(
    () => commandRegistryNames("macro_rules! m\n$callback! {\n one,\n one,\n }", "m"),
    /duplicates: one/,
  );
  expectFailure(
    () => commandRegistryNames("macro_rules! m\n$callback! {\n one => hidden,\n }", "m"),
    /unrecognized shared command registry syntax/,
  );
  // A section comment is not syntax and must not be mistaken for it.
  assertSameSet(
    ["one", "two"],
    commandRegistryNames("macro_rules! m\n$callback! {\n // §3.1\n one,\n two,\n }", "m"),
    "commented registry",
  );

  expectFailure(
    () => defaultPermissionIds('[default]\ndescription = "x"\n'),
    /has no `permissions` array/,
  );
  expectFailure(() => defaultPermissionIds("permissions = [\n]\n"), /grants nothing/);
  assertSameSet(
    ["allow-a", "allow-b"],
    defaultPermissionIds('permissions = [\n  "allow-a",\n  "allow-b",\n]\n'),
    "default.toml parsing",
  );

  // The two new links, each proved to fail on the thing it exists to catch.
  expectFailure(
    () =>
      assertSameSet(
        ["allow-one", "allow-two"],
        defaultPermissionIds('permissions = [\n  "allow-one",\n]\n'),
        "registered commands and permissions/default.toml",
      ),
    /missing: allow-two/,
  );
  expectFailure(
    () =>
      capabilityIdentifiers(
        { permissions: [{ identifier: "zcash:allow-create-wallet", allow: [] }] },
        "zcash",
        "fixture.json",
      ),
    /take none/,
  );
  expectFailure(
    () => capabilityIdentifiers({ permissions: ["core:default", 7] }, "zcash", "fixture.json"),
    /no identifier/,
  );

  expectFailure(
    () =>
      checkPlugin({
        directory: "wallet/plugins/tauri-plugin-zcash",
        namespace: "zcash",
        macro: "with_zcash_commands",
        capabilities: [],
        capabilitiesPending: "too short",
        trackedSchemas: null,
      }),
    /records no substantive reason/,
  );

  expectFailure(
    () =>
      assertIdentical(
        [
          { name: "linux", contents: Buffer.from("current") },
          { name: "macOS", contents: Buffer.from("stale") },
        ],
        "target schemas",
      ),
    /target schemas differ: linux, macOS/,
  );
  const discoveredSchemas = schemaNamesFromTrackedPaths(
    "wallet/zuuallet/src-tauri/gen/schemas/linux-schema.json\n" +
      "wallet/zuuallet/src-tauri/gen/schemas/windows-schema.json\n",
    "wallet/zuuallet/src-tauri/gen/schemas",
    "Zuuallet",
  );
  assertSameSet(
    ["linux-schema.json", "windows-schema.json"],
    discoveredSchemas,
    "dynamic target schema discovery",
  );
  expectFailure(
    () => schemaNamesFromTrackedPaths("", "wallet/zuuallet/src-tauri/gen/schemas", "Zuuallet"),
    /no tracked Zuuallet target schemas/,
  );
  // Registration completeness: a plugin nobody registered must be named.
  expectFailure(
    () =>
      assertSameSet(
        ["wallet/plugins/tauri-plugin-zcash", "wallet/plugins/tauri-plugin-new"],
        ["wallet/plugins/tauri-plugin-zcash"],
        "tracked plugins and PLUGINS",
      ),
    /missing: wallet\/plugins\/tauri-plugin-new/,
  );
  console.log("Tauri plugin permission parity negative controls passed.");
}

if (process.argv.includes("--self-test")) {
  selfTest();
  process.exit(0);
}

assertSameSet(
  trackedPluginDirectories(),
  unique(
    PLUGINS.map((plugin) => plugin.directory),
    "registered plugin directories",
  ),
  "tracked plugins and PLUGINS",
);

const summary = PLUGINS.map((plugin) => {
  const { commands, permissionIds, schemas } = checkPlugin(plugin);
  return (
    `${plugin.namespace}: ${commands.length} commands, ${permissionIds.length} permission ` +
    `identifiers, ${plugin.capabilities.length} capability grants, ` +
    `${schemas.length} tracked target schemas`
  );
});

console.log(`Tauri plugin permission generation matches.\n  ${summary.join("\n  ")}`);
