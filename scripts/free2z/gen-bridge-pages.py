#!/usr/bin/env python3
"""Render Free2Z app-link fallback pages from explicit deployment configuration.

Templates and committed public pages live in ts/free2z/bridge. The caller supplies
--config with contact and store-link values; private deployment values are not
part of this generator. Use --check to detect changed or unexpected output pages.
"""

from __future__ import annotations

import argparse
import html
import json
import os
import re
import string
import sys
import urllib.parse

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BASE = os.path.join(REPO_ROOT, "ts", "free2z", "bridge")
TEMPLATES = os.path.join(BASE, "templates")
DEFAULT_OUT_DIR = os.path.join(BASE, "site")

APPS = ("e2e2z", "zuuli", "free2z")
PLATFORMS = (("ios", "iPhone"), ("android", "Android"))

# Only real store hosts may appear as install buttons. Anything else in the
# config is a hard error rather than a link to wherever someone pasted.
ALLOWED_HOSTS = {
    "testflight": {"testflight.apple.com"},
    "app-store": {"apps.apple.com"},
    "play-internal": {"play.google.com"},
    "play": {"play.google.com"},
}
BUTTON_LABEL = {
    "testflight": "Join the {name} test on TestFlight",
    "app-store": "Get {name} on the App Store",
    "play-internal": "Join the {name} test on Google Play",
    "play": "Get {name} on Google Play",
}
UNLINKED_TEXT = {
    "testflight": "invitation only, through TestFlight. Ask for access below.",
    "app-store": "coming to the App Store.",
    "play-internal": "invitation only, through Google Play internal testing. Ask for access below.",
    "play": "coming to Google Play.",
}
EMAIL_RE = re.compile(r"^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$")
SAFE_TEXT_RE = re.compile(r"^[A-Za-z0-9 ,.'()-]+$")

GENERATED_NOTICE = 'GENERATED by scripts/free2z/gen-bridge-pages.py from ts/free2z/bridge/templates and explicit install configuration. Do not edit generated pages.'


class GeneratorError(Exception):
    pass


def load_config(path):
    try:
        with open(path, encoding="utf-8") as handle:
            config = json.load(handle)
    except (OSError, ValueError) as exc:
        raise GeneratorError("could not read %s: %s" % (path, exc))

    contact = config.get("accessContact")
    if not isinstance(contact, str) or not EMAIL_RE.match(contact):
        raise GeneratorError("%s: accessContact must be an email address" % path)

    apps = config.get("apps")
    if not isinstance(apps, dict) or set(apps) != set(APPS):
        raise GeneratorError(
            "%s: apps must name exactly %s" % (path, ", ".join(APPS))
        )
    for slug in APPS:
        app = apps[slug]
        for key in ("name", "role"):
            if not isinstance(app.get(key), str) or not SAFE_TEXT_RE.match(app[key]):
                raise GeneratorError(
                    "%s: apps.%s.%s must be plain text" % (path, slug, key)
                )
        for platform, _label in PLATFORMS:
            entry = app.get(platform)
            if not isinstance(entry, dict):
                raise GeneratorError("%s: apps.%s.%s missing" % (path, slug, platform))
            channel = entry.get("channel")
            if channel not in ALLOWED_HOSTS:
                raise GeneratorError(
                    "%s: apps.%s.%s.channel %r is not one of %s"
                    % (path, slug, platform, channel, ", ".join(sorted(ALLOWED_HOSTS)))
                )
            if (platform == "ios") != (channel in ("testflight", "app-store")):
                raise GeneratorError(
                    "%s: apps.%s.%s.channel %r is for the other platform"
                    % (path, slug, platform, channel)
                )
            url = entry.get("url")
            if url is None:
                continue
            if not isinstance(url, str):
                raise GeneratorError("%s: apps.%s.%s.url must be a string or null" % (path, slug, platform))
            parsed = urllib.parse.urlsplit(url)
            if (
                parsed.scheme != "https"
                or parsed.hostname not in ALLOWED_HOSTS[channel]
                or parsed.username
                or parsed.password
                or parsed.port is not None
                or parsed.fragment
            ):
                raise GeneratorError(
                    "%s: apps.%s.%s.url %r must be https://%s/..."
                    % (path, slug, platform, url, "|".join(sorted(ALLOWED_HOSTS[channel])))
                )
    return config


def install_block(app):
    rows = []
    for platform, label in PLATFORMS:
        entry = app[platform]
        channel = entry["channel"]
        if entry["url"]:
            rows.append(
                '<div class="store"><span class="store-label">%s:</span> '
                '<a class="button primary" href="%s" rel="noreferrer">%s</a></div>'
                % (
                    label,
                    html.escape(entry["url"], quote=True),
                    html.escape(BUTTON_LABEL[channel].format(name=app["name"])),
                )
            )
        else:
            rows.append(
                '<p class="store"><span class="store-label">%s:</span> %s</p>'
                % (label, html.escape(UNLINKED_TEXT[channel]))
            )
    return "\n".join(rows)


def access_mailto(contact, app_name):
    query = urllib.parse.urlencode(
        {"subject": "Tester access: %s" % app_name}, quote_via=urllib.parse.quote
    )
    return html.escape("mailto:%s?%s" % (contact, query), quote=True)


def read_template(name):
    with open(os.path.join(TEMPLATES, name), encoding="utf-8") as handle:
        return string.Template(handle.read())


def render(config):
    """Return {filename: html}."""
    apps = config["apps"]
    contact = config["accessContact"]
    pages = {}

    chat = read_template("e2e2z-chat.html")
    pages["e2e2z-chat.html"] = chat.substitute(
        generated_notice=GENERATED_NOTICE,
        install_e2e2z=install_block(apps["e2e2z"]),
        install_zuuli=install_block(apps["zuuli"]),
        access_mailto=access_mailto(contact, "e2e2z and ZUULI"),
        contact=html.escape(contact),
    )

    fallback = read_template("app-fallback.html")
    for slug in APPS:
        app = apps[slug]
        pages["%s.html" % slug] = fallback.substitute(
            generated_notice=GENERATED_NOTICE,
            app_slug=slug,
            app_name=html.escape(app["name"]),
            app_role=html.escape(app["role"]),
            install_app=install_block(app),
            access_mailto=access_mailto(contact, app["name"]),
            contact=html.escape(contact),
        )
    return pages


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", required=True)
    parser.add_argument("--out-dir", default=DEFAULT_OUT_DIR)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    try:
        pages = render(load_config(args.config))
    except (GeneratorError, KeyError, ValueError) as exc:
        sys.stderr.write("gen-bridge-pages: %s\n" % exc)
        return 2

    existing = set()
    if os.path.isdir(args.out_dir):
        existing = {n for n in os.listdir(args.out_dir) if n.endswith(".html")}

    if args.check:
        stale = sorted(existing - set(pages))
        drift = []
        for name, body in sorted(pages.items()):
            path = os.path.join(args.out_dir, name)
            try:
                with open(path, encoding="utf-8") as handle:
                    if handle.read() != body:
                        drift.append(name)
            except OSError:
                drift.append(name)
        if drift or stale:
            sys.stderr.write(
                "gen-bridge-pages: %s out of date (%s). Run the generator with the same --config "
                "and commit the result.\n"
                % (args.out_dir, ", ".join(drift + ["stale " + s for s in stale]))
            )
            return 1
        return 0

    os.makedirs(args.out_dir, exist_ok=True)
    for name in existing - set(pages):
        os.remove(os.path.join(args.out_dir, name))
    for name, body in pages.items():
        with open(os.path.join(args.out_dir, name), "w", encoding="utf-8") as handle:
            handle.write(body)
    sys.stderr.write(
        "gen-bridge-pages: wrote %s\n" % ", ".join(sorted(pages))
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
