#!/usr/bin/env bash
# Free2Z application check: gen openapi.
set -euo pipefail

# Resolve the repo root so this works from any cwd (and from a git worktree).
REPO_ROOT="$(git -C "$(dirname "${BASH_SOURCE[0]}")" rev-parse --show-toplevel)"
PY_DIR="${REPO_ROOT}/py/free2z"
OUT_FILE="${REPO_ROOT}/py/free2z/dj/free2z/openapi/f2z.yaml"

cd "${PY_DIR}"
export PYTHONPATH="${PY_DIR}:${PYTHONPATH:-}"
export DJANGO_SETTINGS_MODULE="dj.free2z.settings"

# --- Deterministic environment ------------------------------------------------
# Fixed hash seed (dict/set iteration), C locale (stable, byte-order sorting) and
# UTC keep the generated bytes reproducible regardless of the host's settings.
export PYTHONHASHSEED=0
export LC_ALL=C
export LANG=C
export TZ=UTC
# Force the Postgres backend so integer field formats (int32/int64) match CI and
# production. Honored by settings.py; needs no running database.
export OPENAPI_GEN=1

# --- Toolchain guard: installed versions must match the pins ------------------
# Keep local == CI. If your env drifts, the spec would too; fail early with a
# clear message instead of producing output CI will reject.
python - "${PY_DIR}/requirements/main.txt" <<'PY'
import re, sys

req_file = sys.argv[1]
# Packages whose versions materially affect the generated OpenAPI bytes.
pinned = {
    "django": None,
    "djangorestframework": None,
    "drf_spectacular": None,
}
norm = lambda s: s.lower().replace("-", "_")
with open(req_file) as fh:
    for line in fh:
        line = line.split("#", 1)[0].strip()
        m = re.match(r"^([A-Za-z0-9_.\-\[\]]+)==([0-9][^\s;]*)", line)
        if not m:
            continue
        name = norm(re.sub(r"\[.*\]$", "", m.group(1)))
        if name in pinned:
            pinned[name] = m.group(2)

try:
    from importlib.metadata import version, PackageNotFoundError
except ImportError:  # pragma: no cover
    from importlib_metadata import version, PackageNotFoundError

dist = {  # importable module -> PyPI distribution name
    "django": "Django",
    "djangorestframework": "djangorestframework",
    "drf_spectacular": "drf-spectacular",
}
problems = []
for pkg, want in pinned.items():
    if want is None:
        problems.append(f"could not find a pin for '{pkg}' in {req_file}")
        continue
    try:
        have = version(dist[pkg])
    except PackageNotFoundError:
        problems.append(f"{pkg}: not installed (need {want})")
        continue
    if have != want:
        problems.append(f"{pkg}: installed {have}, requirements pin {want}")

if problems:
    sys.stderr.write(
        "\n[gen-openapi] toolchain mismatch -- the OpenAPI generator is version\n"
        "sensitive and must match py/free2z/requirements/main.txt so local output equals\n"
        "CI. Fix your environment (pip install -r py/free2z/requirements/main.txt):\n"
        + "".join(f"  - {p}\n" for p in problems)
    )
    sys.exit(1)
PY

python dj/free2z/manage.py spectacular \
  --file "${OUT_FILE}" \
  --validate

echo "OpenAPI spec written to ${OUT_FILE}"
